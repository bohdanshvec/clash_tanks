require "json"
require "net/http"
require "timeout"
require "uri"

module DecisionProviders
  class GroqAdapter
    class ConfigurationError < StandardError
    end

    class RequestError < StandardError
    end

    API_URL = "https://api.groq.com/openai/v1/chat/completions"
    DEFAULT_MODEL = "openai/gpt-oss-20b"

    DEFAULT_REASONING_EFFORT = "low"
    DEFAULT_MAX_COMPLETION_TOKENS = 512

    MAX_RATE_LIMIT_RETRIES = 3

    INSTRUCTIONS = <<~TEXT.freeze
      You are the AI decision provider for Clash Tanks, a turn-based
      tank card strategy game.

      You receive:
      1. The visible game state.
      2. A list of legal actions generated by the server.

      Your task is to choose exactly one action from the legal_actions list.

      Return only a JSON object in this format:
      {
        "action_index": 0
      }

      Rules:
      - action_index must be an integer index into the legal_actions array.
      - Choose an index that exists in the supplied array.
      - Never create, modify, or rewrite an action.
      - Never invent action types, payload fields, card IDs, or coordinates.
      - Never return the action itself. Return only action_index.
      - Use only the visible game state. Do not guess hidden opponent cards.
      - Consider attacks, movement, card deployment, available resources,
        unit characteristics, and protection of your headquarters.
      - Prefer a useful legal action when one is available.
      - Choose end_turn when no useful action remains.
      - Do not surrender unless explicitly instructed to do so.
      - Do not return player_id.
      - Do not include explanations, Markdown, or additional fields.

      The server will map your selected index to the exact action object.
      The game engine will independently validate the action.
    TEXT

    def initialize(
      api_key: ENV["GROQ_API_KEY"],
      model: ENV.fetch("GROQ_MODEL", DEFAULT_MODEL),
      reasoning_effort: DEFAULT_REASONING_EFFORT,
      max_completion_tokens: DEFAULT_MAX_COMPLETION_TOKENS,
      http_transport: nil,
      sleeper: nil
    )
      @api_key = api_key
      @model = model
      @reasoning_effort = reasoning_effort
      @max_completion_tokens = max_completion_tokens
      @http_transport = http_transport
      @sleeper = sleeper || ->(seconds) { sleep(seconds) }

      if @api_key.blank?
        raise ConfigurationError, "GROQ_API_KEY is not configured"
      end

      unless %w[none low medium high].include?(@reasoning_effort)
        raise ConfigurationError, "Invalid reasoning_effort: #{@reasoning_effort}"
      end

      unless @max_completion_tokens.is_a?(Integer) &&
             @max_completion_tokens.positive?
        raise ConfigurationError,
              "max_completion_tokens must be a positive integer"
      end
    end

    def call(visible_state)
      legal_actions = DecisionProviders::ActionOptions.call(visible_state)

      if legal_actions.empty?
        raise RequestError, "No legal AI actions available"
      end

      uri = URI(API_URL)

      request = Net::HTTP::Post.new(uri)
      request["Authorization"] = "Bearer #{@api_key}"
      request["Content-Type"] = "application/json"

      # available_actions уже использованы для построения legal_actions.
      # Не отправляем их второй раз внутри game_state.
      game_state_for_model = visible_state.except("available_actions")

      request.body = JSON.generate(
        model: @model,
        reasoning_effort: @reasoning_effort,
        max_completion_tokens: @max_completion_tokens,
        messages: [
          {
            role: "system",
            content: INSTRUCTIONS
          },
          {
            role: "user",
            content: JSON.generate(
              game_state: game_state_for_model,
              legal_actions: legal_actions
            )
          }
        ],
				response_format: {
					type: "json_schema",
					json_schema: {
						name: "ai_action_selection",
						strict: true,
						schema: {
							type: "object",
							properties: {
								action_index: {
								  type: "integer"
								}
							},
							required: ["action_index"],
							additionalProperties: false
						}
					}
				}
      )

      response = send_request_with_rate_limit_retries(uri, request)

      unless response.code.to_i.between?(200, 299)
        log_http_error(response)
        raise RequestError, "Groq API returned HTTP #{response.code}"
      end

      log_token_usage(response.body)

      decision = parse_response(response.body)
      action_index = decision["action_index"]

      unless action_index.is_a?(Integer) &&
             action_index.between?(0, legal_actions.length - 1)
        raise RequestError, "Groq API returned an invalid action index"
      end

      legal_actions.fetch(action_index)
    rescue ConfigurationError, RequestError
      raise
    rescue Net::OpenTimeout, Net::ReadTimeout, Timeout::Error => error
      raise RequestError, "Groq API request timed out: #{error.class}"
    rescue SocketError, SystemCallError, IOError => error
      raise RequestError, "Groq API connection failed: #{error.class}"
    rescue JSON::ParserError
      raise RequestError, "Groq API returned invalid JSON"
    end

    private

    def send_request_with_rate_limit_retries(uri, request)
      retries = 0

      loop do
        response = send_request(uri, request)

        if response.code.to_i.between?(200, 299)
          return response
        end

        unless response.code.to_i == 429
          log_http_error(response)
          raise RequestError, "Groq API returned HTTP #{response.code}"
        end

        retry_delay = rate_limit_retry_delay(response)

        if retry_delay.nil? || retries >= MAX_RATE_LIMIT_RETRIES
          log_http_error(response)

          raise RequestError,
                "Groq API returned HTTP 429 after #{retries} retries"
        end

        retries += 1

        Rails.logger.warn(
          "[GroqAdapter] HTTP 429. " \
          "Retry #{retries}/#{MAX_RATE_LIMIT_RETRIES} " \
          "after #{retry_delay} seconds."
        )

        @sleeper.call(retry_delay)
      end
    end

    def rate_limit_retry_delay(response)
      retry_after = response_header(response, "retry-after")

      if retry_after.present?
        delay = Float(retry_after, exception: false)
        return delay if delay&.positive?
      end

      body = response.body.to_s
      match = body.match(/try again in ([\d.]+)s/i)

      return nil unless match

      delay = Float(match[1], exception: false)
      delay if delay&.positive?
    end

    def response_header(response, name)
      response[name]
    rescue NameError, TypeError, IndexError
      nil
    end

    def log_http_error(response)
      error_details = [
        "HTTP #{response.code}",
        "retry-after=#{response_header(response, 'retry-after').inspect}",
        "remaining-requests=#{response_header(response, 'x-ratelimit-remaining-requests').inspect}",
        "remaining-tokens=#{response_header(response, 'x-ratelimit-remaining-tokens').inspect}",
        "body=#{response.body.to_s.truncate(2000)}"
      ].join("; ")

      Rails.logger.error("[GroqAdapter] #{error_details}")
    end

    def log_token_usage(body)
      data = JSON.parse(body)
      usage = data["usage"]

      unless usage.is_a?(Hash)
        Rails.logger.info(
          "[GroqAdapter] Token usage unavailable for model #{@model}"
        )
        return
      end

      prompt_tokens = usage["prompt_tokens"]
      completion_tokens = usage["completion_tokens"]
      total_tokens = usage["total_tokens"]

      reasoning_tokens = usage.dig(
        "completion_tokens_details",
        "reasoning_tokens"
      )

      finish_reason = data.dig(
        "choices",
        0,
        "finish_reason"
      )

      Rails.logger.info(
        "[GroqAdapter] Token usage: " \
        "model=#{@model}, " \
        "reasoning_effort=#{@reasoning_effort}, " \
        "max_completion_tokens=#{@max_completion_tokens}, " \
        "prompt_tokens=#{prompt_tokens.inspect}, " \
        "completion_tokens=#{completion_tokens.inspect}, " \
        "reasoning_tokens=#{reasoning_tokens.inspect}, " \
        "total_tokens=#{total_tokens.inspect}, " \
        "finish_reason=#{finish_reason.inspect}"
      )
    rescue JSON::ParserError
      Rails.logger.warn("[GroqAdapter] Could not parse token usage")
    end

    def send_request(uri, request)
      if @http_transport
        @http_transport.call(uri, request)
      else
        Net::HTTP.start(
          uri.host,
          uri.port,
          use_ssl: true,
          open_timeout: 5,
          read_timeout: 20
        ) do |http|
          http.request(request)
        end
      end
    end

    def parse_response(body)
      data = JSON.parse(body)
      content = data.dig("choices", 0, "message", "content")

      unless content.is_a?(String) && content.present?
        raise RequestError, "Groq API response does not contain a decision"
      end

      begin
        decision = JSON.parse(content)
      rescue JSON::ParserError
        raise RequestError, "Groq API returned an invalid decision"
      end

      unless decision.is_a?(Hash)
        raise RequestError, "Groq API decision must be a JSON object"
      end

      decision
    rescue JSON::ParserError
      raise RequestError, "Groq API returned invalid JSON"
    end
  end
end
